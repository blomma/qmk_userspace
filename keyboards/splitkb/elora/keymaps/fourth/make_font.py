#!/usr/bin/env python3
"""Generates big_font.h, the large font on the layer screen.

Reads a 1bpp QFF font, the Quantum Painter font the Halcyon displays use, and
writes the glyphs a stacked layer name can show as columns of pixels that
display.c draws straight into the OLED buffer. The layer screen stacks the
name in capitals, so the font stops before the lowercase letters and every
glyph is cropped to the height of the capitals and to the width of its ink.
A glyph that reaches above or below the capitals is replaced with '?'.

Run from this directory:

    python3 make_font.py
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / '../../../../../users/halcyon_modules/splitkb/hlc_tft_display/graphics/fonts/Retron2000-27.qff.c'
OUTPUT = HERE / 'big_font.h'

# Space up to the backtick, the last character before the lowercase letters
FIRST, LAST = 0x20, 0x60


def u(b):
    return int.from_bytes(b, 'little')


def read_qff(path):
    src = path.read_text()
    body = src[src.index('] = {'):]
    return bytes(int(h, 16) for h in re.findall(r'0x([0-9A-Fa-f]{2})', body))


def check_block(data, pos, type_id):
    if data[pos] != type_id or data[pos + 1] != (~type_id & 0xFF):
        sys.exit(f'expected block type {type_id} at offset {pos}')
    return u(data[pos + 2:pos + 5])


def decode_rle(data, pos, size):
    # QMK RLE: a marker of 128 and up starts marker - 127 literal bytes, a
    # lower marker repeats the next byte marker times
    out = bytearray()
    while len(out) < size:
        marker = data[pos]
        pos += 1
        if marker >= 128:
            out += data[pos:pos + marker - 127]
            pos += marker - 127
        else:
            out += bytes([data[pos]]) * marker
            pos += 1
    return out


def read_glyphs(data):
    """Returns the line height and, for each ASCII glyph, a list of columns
    of pixels, each column a list of line height pixels from the top."""
    # Font descriptor
    if check_block(data, 0, 0x00) != 20 or data[5:8] != b'QFF' or data[8] != 1:
        sys.exit('not a version 1 QFF font')
    line_height = data[17]
    has_ascii = data[18]
    num_unicode = u(data[19:21])
    fmt, compression = data[21], data[23]
    if not has_ascii or num_unicode or fmt != 0x00:
        sys.exit('expected a 1bpp font with only the ASCII table')

    # ASCII glyph table, then the font data
    pos = 25
    table = data[pos + 5:pos + 5 + check_block(data, pos, 0x01)]
    pos += 5 + len(table)
    check_block(data, pos, 0x04)
    base = pos + 5

    glyphs = {}
    for i in range(0x7E - 0x20 + 1):
        entry = u(table[i * 3:i * 3 + 3])
        width, offset = entry & 0x3F, entry >> 6
        count = width * line_height
        size = (count + 7) // 8
        if compression:
            raw = decode_rle(data, base + offset, size)
        else:
            raw = data[base + offset:base + offset + size]
        # Pixels run row by row, least significant bit first
        pixels = [(raw[n // 8] >> (n % 8)) & 1 for n in range(count)]
        glyphs[chr(0x20 + i)] = [[pixels[r * width + c] for r in range(line_height)] for c in range(width)]
    return line_height, glyphs


def inked_rows(glyph):
    return [r for col in glyph for r in range(len(col)) if col[r]]


def main():
    _, glyphs = read_glyphs(read_qff(SOURCE))

    caps = inked_rows(glyphs['H'])
    top, bottom = min(caps), max(caps)
    height = bottom - top + 1
    if height > 32:
        sys.exit(f'capitals are {height} rows tall, more than fits in a column')

    def fits(glyph):
        rows = inked_rows(glyph)
        return not rows or (min(rows) >= top and max(rows) <= bottom)

    if not fits(glyphs['?']):
        sys.exit("'?' has to fit, it stands in for the glyphs that don't")

    columns, offsets, replaced = [], [], []
    for code in range(FIRST, LAST + 1):
        glyph = glyphs[chr(code)]
        if not fits(glyph):
            replaced.append(chr(code))
            glyph = glyphs['?']
        offsets.append(len(columns))
        bits = [sum(1 << (r - top) for r in range(top, bottom + 1) if col[r]) for col in glyph]
        # Drop the blank columns on either side, a space keeps none
        inked = [i for i, b in enumerate(bits) if b]
        if inked:
            columns += bits[inked[0]:inked[-1] + 1]
    offsets.append(len(columns))

    lines = [
        f'// Generated by make_font.py from {SOURCE.name}, do not edit.',
        '',
        '#pragma once',
        '',
        '#include <stdint.h>',
        '#include "progmem.h"',
        '',
        f'#define BIG_FONT_HEIGHT {height}',
        f'#define BIG_FONT_FIRST 0x{FIRST:02X}',
        f'#define BIG_FONT_LAST 0x{LAST:02X}',
        f'#define BIG_FONT_MAX_WIDTH {max(b - a for a, b in zip(offsets, offsets[1:]))}',
        '',
        '// Glyph c spans columns big_font_offsets[c - BIG_FONT_FIRST] up to the next',
        '// offset, cropped to its ink. Bit n of a column is pixel row n, counted',
        "// from the top of the capitals. These glyphs don't fit and show '?': "
        + ' '.join(replaced),
        '// clang-format off',
        f'static const uint16_t PROGMEM big_font_offsets[{len(offsets)}] = {{',
    ]
    for i in range(0, len(offsets), 12):
        lines.append('    ' + ' '.join(f'{o:4d},' for o in offsets[i:i + 12]))
    lines += ['};', '', f'static const uint32_t PROGMEM big_font_columns[{len(columns)}] = {{']
    for i, code in enumerate(range(FIRST, LAST + 1)):
        cols = columns[offsets[i]:offsets[i + 1]]
        if not cols:
            continue
        lines.append(f"    // '{chr(code)}'" if chr(code) != '\\' else '    // backslash')
        for j in range(0, len(cols), 6):
            lines.append('    ' + ' '.join(f'0x{c:08X},' for c in cols[j:j + 6]))
    lines += ['};', '// clang-format on', '']

    OUTPUT.write_text('\n'.join(lines))
    print(f'wrote {OUTPUT.name}: {height} rows, {len(columns)} columns, replaced {replaced}')


if __name__ == '__main__':
    main()
